create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  auth_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null,
  email text not null unique,
  role text not null default 'student' check (role in ('student', 'admin', 'super_admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Campus',
  source text not null,
  published text not null default 'Just now',
  priority text not null default 'Update' check (priority in ('Important', 'Update', 'Opportunity')),
  created_at timestamptz not null default now()
);

create table if not exists public.clubs (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Community',
  members integer not null default 0 check (members >= 0),
  description text not null default '',
  verified boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  type text not null default 'Community',
  "when" text not null default 'Date to be announced',
  place text not null default 'UTAMU campus',
  registrations integer not null default 0 check (registrations >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.groups (
  id bigint generated by default as identity primary key,
  name text not null,
  detail text not null default '',
  members integer not null default 0 check (members >= 0),
  visibility text not null default 'public' check (visibility in ('public', 'private')),
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups(id) on delete cascade,
  author text not null,
  body text not null,
  created_at text not null default 'Just now'
);

alter table public.profiles enable row level security;
alter table public.announcements enable row level security;
alter table public.clubs enable row level security;
alter table public.events enable row level security;
alter table public.groups enable row level security;
alter table public.messages enable row level security;

create policy "public can read published campus content" on public.announcements for select using (true);
create policy "public can read clubs" on public.clubs for select using (true);
create policy "public can read events" on public.events for select using (true);
create policy "authenticated users can read groups" on public.groups for select to authenticated using (true);
create policy "authenticated users can read group messages" on public.messages for select to authenticated using (true);
create policy "users can read their profile" on public.profiles for select to authenticated using (auth_id = auth.uid());
